#!/usr/bin/env node
/**
 * Bake a Figma screen into @lab/ui delivery assets.
 *
 * Copies contract JSON + writes a React component that renders real DOM
 * via FigmaContractScreen (render-html), not a flat PNG.
 * Keeps reference + Figma live PNGs for pipeline comparison artifacts.
 *
 *   node scripts/bake-figma-screen-ui.mjs --screen screen_1 --component Screen1
 */

import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { safeScreenSegment } from "./figma-screen-portfolio.mjs";

const WORKSPACE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCREENS_DIR = join(WORKSPACE, "artifacts/figma-screens");
const DIFFS_DIR = join(WORKSPACE, "figma-screen-diffs");
const require = createRequire(import.meta.url);
const _pngjs = require("pngjs");
const { PNG } = _pngjs.PNG ? _pngjs : (_pngjs.default ?? _pngjs);

function metaExportName(component) {
  const snake = component
    .replace(/([A-Z])/g, "_$1")
    .replace(/^_/, "")
    .toUpperCase();
  return `${snake}_META`;
}

function cssFileName(component) {
  return component
    .replace(/([A-Z])/g, "-$1")
    .replace(/^-/, "")
    .toLowerCase();
}

function componentTsx({ screen, component, metaName, cssFile }) {
  return `import React from "react";
import { FigmaContractScreen, type ContractDocument } from "../../contract/FigmaContractScreen";
import rawContract from "./contract.json";
import { ${metaName} } from "./baked.meta";
import "./${cssFile}";

const contract = rawContract as ContractDocument;

/**
 * Figma-imported screen (${screen}).
 * Real DOM from contract JSON (render-html) — not a baked PNG surface.
 * Re-bake via \`node scripts/bake-figma-screen-ui.mjs --screen ${screen} --component ${component}\`.
 */
export function ${component}() {
  return (
    <FigmaContractScreen
      contract={contract}
      meta={${metaName}}
      componentName="${component}"
    />
  );
}
`;
}

function parseCli() {
  const args = new Map();
  for (let i = 2; i < process.argv.length; i++) {
    const v = process.argv[i];
    if (v.startsWith("--") && i + 1 < process.argv.length && !process.argv[i + 1].startsWith("--")) {
      args.set(v.slice(2), process.argv[i + 1]);
      i++;
    }
  }
  const screen = args.get("screen") ?? "screen_1";
  const component = args.get("component") ?? "Screen1";
  return { screen, component };
}

async function main() {
  const { screen, component } = parseCli();
  const manifestPath = join(SCREENS_DIR, `${screen}.manifest.json`);
  const contractPath = join(SCREENS_DIR, `${screen}.contract.json`);
  const pngPath = join(SCREENS_DIR, `${screen}.png`);
  const figmaRenderedCandidates = [
    join(DIFFS_DIR, safeScreenSegment(screen), "rendered.png"),
    join(DIFFS_DIR, safeScreenSegment(screen), "originalParity", "figmaLive.png"),
    join(DIFFS_DIR, "by-screen", safeScreenSegment(screen), "contractFigma", "rendered.png"),
  ];
  const figmaRenderedPath = figmaRenderedCandidates.find((p) => existsSync(p));
  const outDir = join(WORKSPACE, "packages/ui/src/components", component);
  const metaName = metaExportName(component);
  const cssFile = `${cssFileName(component)}.css`;

  if (!existsSync(manifestPath)) {
    console.error(`✗ Missing manifest: ${manifestPath}`);
    process.exit(1);
  }
  if (!existsSync(contractPath)) {
    console.error(
      `✗ Missing contract: ${contractPath}\n  Run Manifest → Contract first (pnpm test:figma:screen:manifest -- --artifact ${manifestPath})`
    );
    process.exit(1);
  }
  if (!figmaRenderedPath) {
    console.error(
      `✗ Missing Figma live PNG for ${screen}\n  Tried:\n${figmaRenderedCandidates.map((p) => `    ${p}`).join("\n")}\n  Run Contract → Figma first.`
    );
    process.exit(1);
  }
  if (!existsSync(pngPath)) {
    console.error(`✗ Missing reference PNG: ${pngPath}`);
    process.exit(1);
  }

  const refBuf = await readFile(pngPath);
  const refPng = PNG.sync.read(refBuf);
  const figmaBuf = await readFile(figmaRenderedPath);
  const figmaPng = PNG.sync.read(figmaBuf);
  let background = "#ffffff";
  try {
    if (existsSync(contractPath)) {
      const doc = JSON.parse(await readFile(contractPath, "utf8"));
      background = doc.meta?.canvasBackground ?? background;
    }
  } catch {
    /* ok */
  }

  const meta = {
    width: refPng.width,
    height: refPng.height,
    background,
    screenId: screen,
    figmaRenderedAt: new Date().toISOString(),
  };

  await mkdir(outDir, { recursive: true });
  await copyFile(contractPath, join(outDir, "contract.json"));
  await copyFile(pngPath, join(outDir, "figma-export.png"));
  await copyFile(figmaRenderedPath, join(outDir, "figma-live-export.png"));
  await writeFile(
    join(outDir, "baked.meta.ts"),
    `/** Generated by scripts/bake-figma-screen-ui.mjs — do not edit */\nexport const ${metaName} = ${JSON.stringify(meta, null, 2)} as const;\n`,
    "utf8"
  );
  await writeFile(join(outDir, `${component}.tsx`), componentTsx({ screen, component, metaName, cssFile }), "utf8");

  console.log(`✓ Baked ${screen} → packages/ui/src/components/${component}/`);
  console.log(`  contract.json + ${component}.tsx (FigmaContractScreen / render-html)`);
  console.log(`  figma-export.png: ${refPng.width}×${refPng.height}px (reference artifact)`);
  console.log(`  figma-live-export.png: ${figmaPng.width}×${figmaPng.height}px (Contract → Figma live)`);
}

main().catch((err) => {
  console.error("[bake-figma-screen-ui] Fatal:", err);
  process.exit(1);
});
